def _render_histogram(
    scores: pd.Series,
    bins: int,
    show_density: bool,
    show_mean_line: bool
) -> None:
    """Render an interactive Plotly histogram."""
    try:
        from app.theme import get_chart_colors
        colors = get_chart_colors()
    except Exception:
        colors = {}

    fig = go.Figure()
    histnorm = "probability density" if show_density else None
    y_title = "Density" if show_density else "Count"

    fig.add_trace(
        go.Histogram(
            x=scores,
            nbinsx=bins,
            histnorm=histnorm,
            name="Similarity Scores",
            marker=dict(
                color=colors.get("accent", "#0D9488"),
                line=dict(
                    color=colors.get("card", "#FFFFFF"),
                    width=1
                )
            ),
            hovertemplate="Score Range: %{x}<br>" + f"{y_title}: %{{y}}<extra></extra>"
        )
    )

    if show_mean_line:
        mean_val = float(scores.mean())
        fig.add_vline(
            x=mean_val,
            line_dash="dash",
            line_color=colors.get("danger", "#FF4B4B"),
            annotation_text=f"Mean: {mean_val:.4f}",
            annotation_position="top right",
            annotation_font=dict(color=colors.get("danger", "#FF4B4B"))
        )

    _apply_plotly_theme(
        fig,
        title="Similarity Score Distribution Histogram",
        theme_colors=colors
    )

    fig.update_layout(
        xaxis_title="Similarity Score",
        yaxis_title=y_title,
        bargap=0.05
    )

    st.plotly_chart(fig, use_container_width=True)


