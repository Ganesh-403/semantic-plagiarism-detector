# ── HELPER FUNCTIONS ──────────────────────────────────────────────────────────

def _safe_float(value: Any, default: float = 0.0) -> float:
    """Safely convert a value to float, handling exceptions."""
    if value is None:
        return default
    try:
        return float(value)
    except (ValueError, TypeError):
        return default


def _safe_int(value: Any, default: int = 0) -> int:
    """Safely convert a value to int, handling exceptions."""
    if value is None:
        return default
    try:
        return int(value)
    except (ValueError, TypeError):
        return default


def _compute_statistics(scores: pd.Series) -> Dict[str, float | int]:
    """Compute statistical metrics for the similarity scores."""
    if scores.empty:
        return {
            "total_samples": 0,
            "mean": 0.0,
            "median": 0.0,
            "std_dev": 0.0,
            "variance": 0.0,
            "min_val": 0.0,
            "max_val": 0.0,
            "range_val": 0.0,
        }

    total = len(scores)
    mean_val = float(scores.mean())
    median_val = float(scores.median())
    std_val = float(scores.std()) if total > 1 else 0.0
    var_val = float(scores.var()) if total > 1 else 0.0
    min_val = float(scores.min())
    max_val = float(scores.max())
    range_val = max_val - min_val

    return {
        "total_samples": total,
        "mean": mean_val,
        "median": median_val,
        "std_dev": std_val,
        "variance": var_val,
        "min_val": min_val,
        "max_val": max_val,
        "range_val": range_val,
    }


def _compute_percentiles(scores: pd.Series) -> Dict[str, float]:
    """Compute percentile values for the similarity scores."""
    if scores.empty:
        return {
            "P25": 0.0,
            "P50": 0.0,
            "P75": 0.0,
            "P90": 0.0,
            "P95": 0.0,
            "P99": 0.0,
        }

    # Calculate percentiles using numpy
    p_values = np.percentile(scores, [25, 50, 75, 90, 95, 99])
    return {
        "P25": float(p_values[0]),
        "P50": float(p_values[1]),
        "P75": float(p_values[2]),
        "P90": float(p_values[3]),
        "P95": float(p_values[4]),
        "P99": float(p_values[5]),
    }


def _detect_outliers(scores: pd.Series) -> Dict[str, Any]:
    """Detect outliers in the scores using the Interquartile Range (IQR) method."""
    if scores.empty or len(scores) < 4:
        return {
            "total_outliers": 0,
            "highest_outlier": 0.0,
            "lowest_outlier": 0.0,
            "outlier_percentage": 0.0,
            "q1": 0.0,
            "q3": 0.0,
            "iqr": 0.0,
            "lower_bound": 0.0,
            "upper_bound": 0.0,
        }

    q1 = float(scores.quantile(0.25))
    q3 = float(scores.quantile(0.75))
    iqr = q3 - q1
    lower_bound = q1 - 1.5 * iqr
    upper_bound = q3 + 1.5 * iqr

    outliers = scores[(scores < lower_bound) | (scores > upper_bound)]
    total_outliers = len(outliers)
    outlier_pct = (total_outliers / len(scores)) * 100.0

    highest_outlier = float(outliers.max()) if total_outliers > 0 else 0.0
    lowest_outlier = float(outliers.min()) if total_outliers > 0 else 0.0

    return {
        "total_outliers": total_outliers,
        "highest_outlier": highest_outlier,
        "lowest_outlier": lowest_outlier,
        "outlier_percentage": outlier_pct,
        "q1": q1,
        "q3": q3,
        "iqr": iqr,
        "lower_bound": lower_bound,
        "upper_bound": upper_bound,
    }


def _prepare_dataframe(incidents: List[Any]) -> pd.DataFrame:
    """Convert raw incidents list into a clean Pandas DataFrame with similarity scores."""
    if not incidents:
        return pd.DataFrame(columns=["similarity_score"])

    rows = []
    for inc in incidents:
        is_dict = isinstance(inc, dict)

        def _get_val(key: str, default: Any = None) -> Any:
            if is_dict:
                return inc.get(key, default)
            try:
                return getattr(inc, key, default)
            except AttributeError:
                return default

        # Support both 'similarity_score' and property 'similarity'
        score = _get_val("similarity_score")
        if score is None:
            score = _get_val("similarity")

        rows.append({
            "similarity_score": _safe_float(score, default=0.0)
        })

    return pd.DataFrame(rows)


